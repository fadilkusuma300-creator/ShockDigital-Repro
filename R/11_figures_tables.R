    ggplot2::theme(strip.text = ggplot2::element_text(face = "bold", hjust = 0))
  ggplot2::ggsave(
    path, p, width = f$width_in, height = f$height_in,
    device = grDevices::cairo_pdf
  )
}

severe_outcome_table <- function(fits, cfg) {
  data.table::rbindlist(lapply(names(fits), function(outcome) {
    z <- weighted_dr_effect(fits[[outcome]]$data, quote(severe_shock == 1L))
    scale <- if (outcome == "y_sales") 1 else 100
    ci <- ci_from_estimate(z$estimate, z$se, cfg$inference$pointwise_level)
    data.table::data.table(
      outcome = outcome, estimate = scale * z$estimate, se = scale * z$se,
      lower = scale * ci[1], upper = scale * ci[2], n = z$n
    )
  }))
}

sample_panel_b <- function(windows, balance) {
  # Unadjusted treatment/control summaries shown beside post-adjustment SMDs.
  d <- windows
  get_smd <- function(pattern) {
    z <- balance[grepl(pattern, covariate, fixed = TRUE)]
    if (!nrow(z)) return(NA_real_)
    z$abs_after[which.max(z$abs_after)]
  }
  pct <- function(v, arm) 100 * weighted_mean(as.numeric(v[d$treatment == arm]), d$analysis_weight[d$treatment == arm])
  mean_arm <- function(v, arm) weighted_mean(as.numeric(v[d$treatment == arm]), d$analysis_weight[d$treatment == arm])

  input_decline <- as.integer(d$t0_input_state == 3)
  cash_decline <- as.integer(d$t0_cash_flow_state == 3)
  data.table::data.table(
    variable = c(
      "Number of firms", "Baseline employment, mean", "Firm age, years",
      "Pre-pandemic website, %", "First-wave sales decline, %",
      "First-wave input supply decline, %", "First-wave cash-flow decline, %"
    ),
    treated = c(
      sum(d$treatment == 1L),
      mean_arm(d$baseline_employment, 1), mean_arm(d$firm_age, 1), pct(d$website, 1),
      mean_arm(d$shock_sales_decline, 1), pct(input_decline, 1), pct(cash_decline, 1)
    ),
    control = c(
      sum(d$treatment == 0L),
      mean_arm(d$baseline_employment, 0), mean_arm(d$firm_age, 0), pct(d$website, 0),
      mean_arm(d$shock_sales_decline, 0), pct(input_decline, 0), pct(cash_decline, 0)
    ),
    post_adjustment_smd = c(
      NA_real_, get_smd("baseline_employment"), get_smd("firm_age"), get_smd("website"),
      get_smd("shock_sales_decline"), get_smd("t0_input_state"), get_smd("t0_cash_flow_state")
    )
  )
}
