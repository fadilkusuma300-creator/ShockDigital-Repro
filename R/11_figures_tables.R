save_fig4_secondary_curves <- function(curves, path, reference_shock = NULL,
                                       fig_cfg = load_figure_config()) {
  s <- fig_style(fig_cfg)
  f <- fig_cfg$fig4
  if (is.null(reference_shock)) reference_shock <- f$reference_shock %||% 50
  labels <- c(
    y_continued_operation = "a  Business continuity",
    y_employment_retention = "b  Employment retention",
    y_input_recovery = "c  Input recovery"
  )
  d <- data.table::copy(curves)
  d[, panel := factor(labels[outcome], levels = unname(labels))]
  p <- ggplot2::ggplot(d, ggplot2::aes(x = shock, y = estimate)) +
    ggplot2::geom_hline(yintercept = 0, colour = s$zero, linetype = "dashed", linewidth = as.numeric(f$zero_line_width %||% 0.34)) +
    ggplot2::geom_vline(
      xintercept = reference_shock, colour = s$threshold,
      linetype = "dashed", linewidth = as.numeric(f$reference_line_width %||% 0.45)
    ) +
    ggplot2::geom_ribbon(
      ggplot2::aes(ymin = lower, ymax = upper),
      fill = s$band, alpha = as.numeric(f$band_alpha %||% 0.72), colour = NA
    ) +
    ggplot2::geom_line(colour = s$primary, linewidth = as.numeric(f$line_width %||% 0.72)) +
    ggplot2::facet_wrap(~ panel, scales = "fixed", nrow = 1) +
    ggplot2::scale_x_continuous(breaks = seq(f$x_min, f$x_max, by = f$x_break), expand = c(0, 0)) +
    ggplot2::coord_cartesian(xlim = c(f$x_min, f$x_max), ylim = c(f$y_min, f$y_max)) +
