save_fig2_primary_curve <- function(curve, threshold, path, fig_cfg = load_figure_config()) {
  s <- fig_style(fig_cfg)
  f <- fig_cfg$fig2
  p <- ggplot2::ggplot(curve, ggplot2::aes(x = shock, y = estimate)) +
    ggplot2::geom_hline(yintercept = 0, colour = s$zero, linetype = "dashed", linewidth = as.numeric(f$zero_line_width %||% 0.38)) +
    ggplot2::geom_ribbon(
      ggplot2::aes(ymin = pointwise_lower, ymax = pointwise_upper),
      fill = s$band, alpha = as.numeric(f$band_alpha %||% 0.72), colour = NA
    ) +
    ggplot2::geom_line(colour = s$primary, linewidth = as.numeric(f$line_width %||% 0.85)) +
    ggplot2::scale_x_continuous(breaks = seq(f$x_min, f$x_max, by = f$x_break), expand = c(0, 0)) +
    ggplot2::scale_y_continuous(breaks = seq(f$y_min, f$y_max, by = f$y_break)) +
    ggplot2::coord_cartesian(xlim = c(f$x_min, f$x_max), ylim = c(f$y_min, f$y_max)) +
    ggplot2::labs(
      x = "Initial sales decline at t0 (%)",
      y = "Estimated recovery effect (percentage points)"
    ) + publication_theme(s$base_size, s$font, fig_cfg)
  if (is.finite(threshold)) {
    p <- p + ggplot2::geom_vline(
      xintercept = threshold, colour = s$threshold,
      linetype = "dashed", linewidth = as.numeric(f$threshold_line_width %||% 0.55)
    )
    if (isTRUE(f$show_threshold_point)) {
      j <- which.min(abs(curve$shock - threshold))
      p <- p + ggplot2::geom_point(
        data = curve[j], ggplot2::aes(x = shock, y = estimate),
        inherit.aes = FALSE, colour = s$primary, size = as.numeric(f$threshold_point_size %||% 1.9)
      )
    }
  }
  ggplot2::ggsave(
    path, p, width = f$width_in, height = f$height_in,
    device = grDevices::cairo_pdf
  )
}

