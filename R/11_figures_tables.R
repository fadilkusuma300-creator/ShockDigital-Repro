publication_theme <- function(base_size = 10, font_family = "sans", fig_cfg = load_figure_config()) {
  th <- fig_cfg$theme %||% list()
  margin <- unlist(th$plot_margin_pt %||% c(6, 8, 6, 8))
  ggplot2::theme_minimal(base_size = base_size, base_family = font_family) +
    ggplot2::theme(
      panel.grid.minor = ggplot2::element_blank(),
      panel.grid.major.x = ggplot2::element_blank(),
      panel.grid.major.y = ggplot2::element_line(
        linewidth = as.numeric(th$grid_line_width %||% 0.25),
        colour = th$grid_color %||% "#d9d9d9"
      ),
      axis.title = ggplot2::element_text(size = base_size),
      axis.text = ggplot2::element_text(colour = "black"),
      strip.text = ggplot2::element_text(face = "bold", hjust = 0),
      strip.background = ggplot2::element_blank(),
      legend.position = th$legend_position %||% "bottom",
      plot.margin = ggplot2::margin(margin[1], margin[2], margin[3], margin[4])
    )
}

fig_style <- function(fig_cfg = load_figure_config()) {
  list(
    font = fig_cfg$font_family %||% "sans",
    base_size = as.numeric(fig_cfg$base_size %||% 10),
    primary = fig_cfg$colors$primary %||% "#1f4e79",
    band = fig_cfg$colors$band %||% "#d9e7f3",
    zero = fig_cfg$colors$zero %||% "#6f6f6f",
    threshold = fig_cfg$colors$threshold %||% "#6f6f6f"
  )
}

